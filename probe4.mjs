import { chromium } from "@playwright/test"
const legacy = JSON.parse(process.env.LEGACY)
const b = await chromium.launch()
const page = await b.newPage({ viewport: { width: 1440, height: 1000 } })
await page.route("**/api/**", r => r.fulfill({ json: legacy }))
await page.goto("http://127.0.0.1:4173/models")
await page.waitForTimeout(2000)
const card = page.getByText("Success rate by model", { exact: true }).locator("xpath=ancestor::*[@data-slot='card'][1]")
await card.screenshot({ path: "/tmp/legacy-models.png" })
const txt = await card.innerText()
console.log(txt)
await b.close()
